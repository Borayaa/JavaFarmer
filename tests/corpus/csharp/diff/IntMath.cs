// Integer division and remainder with negatives, casts and Math helpers.
int a = 7;
int b = -7;
Console.WriteLine(a / 2);
Console.WriteLine(b / 2);
Console.WriteLine(a % 3);
Console.WriteLine(b % 3);
Console.WriteLine(a % -3);
Console.WriteLine(b / -2);
Console.WriteLine(-1 / 4);
Console.WriteLine(-9 % 4);
Console.WriteLine((int)2.9);
Console.WriteLine((int)-2.9);
Console.WriteLine((int)(-7 / 2.0));
Console.WriteLine(Math.Abs(b));
Console.WriteLine(Math.Abs(-2.5));
Console.WriteLine(Math.Min(a, b));
Console.WriteLine(Math.Max(3, 4));
Console.WriteLine(Math.Max(1.5, 2));
Console.WriteLine(7 / 2.0);
Console.WriteLine(10 / 4 * 4);
